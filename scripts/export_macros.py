"""Write paper result macros and tables from logged pilot outputs only.

Inputs:  runs/pilot/summary.json, runs/pilot/output_level.json, runs/bench_backends.json,
         runs/pilot/spec.json
Outputs: ../paper-pod/results_macros.tex, ../paper-pod/tables/detection.tex
"""
import json
import sys
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "runs" / "pilot"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _paths import paper_dir, poster_figs  # noqa: E402  (../paper-pod and ../poster, or figures/ standalone)
PAPER = paper_dir()
VERIFIER = "mps-fp32"
CHEATS = [("sub-bk-small", "BK-SDM-Small"), ("sub-bk-tiny", "BK-SDM-Tiny"), ("w8", "8-bit weights"),
          ("w4", "4-bit weights"), ("cfg-skip", "CFG skip"), ("cache2", "Cache (every other)"),
          ("cache2-late", "Cache (late only)"), ("step-skip", "Step skip"), ("neg-strip", "Safety strip")]


def sci(x: float) -> str:
    m, e = f"{x:.1e}".split("e")
    return f"{m}{{\\times}}10^{{{int(e)}}}"


def main():
    sm = json.loads((RUN / "summary.json").read_text())
    ol = json.loads((RUN / "output_level.json").read_text())
    bench = json.loads((ROOT / "runs" / "bench_backends.json").read_text())
    spec = json.loads((RUN / "spec.json").read_text())
    hp = sm["honest_pairs"]
    fp32 = [hp[k] for k in ("cpu-fp32->mps-fp32", "mps-fp32->cpu-fp32") if k in hp]
    mixed = [v for k, v in hp.items() if ("fp16" in k) and k.split("->")[0] != k.split("->")[1]]
    ch = {k.split("@")[0]: v for k, v in sm["cheats"].items() if k.endswith("@" + VERIFIER)}
    steps = spec["spec"]["steps"]
    k = 2
    m = {
        "resNprompts": len(spec["prompts"]),
        "resSteps": steps,
        "resHonestSteps": sm["honest_steps_checked"],
        "resFalseFlags": round(sm["honest_step_false_accusation_rate"] * sm["honest_steps_checked"]),
        "resDriftFPMed": f"${sci(max(v['median'] for v in fp32))}$",
        "resDriftFPMax": f"${sci(max(v['max'] for v in fp32))}$",
        "resDriftMixedMed": f"${sci(max(v['median'] for v in mixed))}$",
        "resDriftMixedMax": f"${sci(max(v['max'] for v in mixed))}$",
        "resCaughtKtwo": sum(v["P_detect_k2_mean"] >= 0.99 for v in ch.values()),
        "resNcheats": len(ch),
        "resWeightEightRatio": f"{ch['w8']['max_ratio_over_honest_max_median']:.1f}",
        "resOutThr": f"{ol['threshold_min_honest_psnr']:.1f}",
        "resOutAccepted": ol["accepted_total"],
        "resOutTotal": ol["cheat_images_total"],
        "resOutLate": ol["cheats"]["cache2-late"]["accepted"],
        "resOutWeight": ol["cheats"]["w8"]["accepted"],
        "resLateKneeded": next(kk for kk in range(1, steps + 1)
                               if 1 - comb(steps - round(ch["cache2-late"]["flagged_step_frac_mean"] * steps), kk) / comb(steps, kk) >= 0.99),
        "resCpuCacheFlag": f"{100 * max(sm['cheats']['cache2@cpu-fp32']['flagged_step_frac_mean'], sm['cheats']['cache2-late@cpu-fp32']['flagged_step_frac_mean']):.0f}",
        "resCpuSteps": ", ".join(str(i) for i in spec["cpu_steps"]),
        "resGpuStep": f"{bench['mps-fp16']['step_s']:.2f}",
        "resCpuStep": f"{bench['cpu-fp32']['step_s']:.2f}",
        "resVerifyCostPct": f"{100 * k / steps:.0f}",
        "resVerifySecs": f"{k * bench['mps-fp16']['step_s']:.1f}",
        "resGenSecs": f"{steps * bench['mps-fp16']['step_s']:.0f}",
    }
    for tag, fname in (("Fp", "browser_debug_unet_fp32_single.json"), ("Half", "browser_debug_unet_fp16_torch.json")):
        bj = ROOT / "runs" / fname
        if bj.exists():
            b = json.loads(bj.read_text())
            m[f"resBrowser{tag}EpsMin"] = f"${sci(min(r['browser_rel'] for r in b['rows']))}$"
            m[f"resBrowser{tag}EpsMax"] = f"${sci(max(r['browser_rel'] for r in b['rows']))}$"
            m[f"resBrowser{tag}Step"] = f"${sci(b['guided_step_r_vs_cpu_fp32'])}$"
            m[f"resOrtHalfEpsMax"] = f"${sci(max(r['ort_cpu_fp16_rel'] for r in b['rows']))}$"
        else:
            for key in ("EpsMin", "EpsMax", "Step"):
                m[f"resBrowser{tag}{key}"] = "\\tbd"
    lines = ["% Generated by pod/scripts/export_macros.py from logged runs. Do not edit by hand."]
    lines += [f"\\newcommand{{\\{name}}}{{{val}\\xspace}}" for name, val in m.items()]
    (PAPER / "results_macros.tex").write_text("\n".join(lines) + "\n")

    rows = ["% Generated by pod/scripts/export_macros.py. Do not edit by hand.",
            "\\begin{tabular}{lccccc}", "\\toprule",
            "Cheat & Flagged steps & $k{=}1$ & $k{=}2$ & $k{=}4$ (worst) & Image test \\\\", "\\midrule"]
    for key, label in CHEATS:
        v, o = ch[key], ol["cheats"][key]
        rows.append(f"{label} & {100 * v['flagged_step_frac_mean']:.0f}\\% & {v['P_detect_k1_mean']:.2f} & "
                    f"{v['P_detect_k2_mean']:.2f} & {v['P_detect_k4_min']:.2f} & {o['accepted']}/{o['n']} pass \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    (PAPER / "tables").mkdir(exist_ok=True)
    (PAPER / "tables" / "detection.tex").write_text("\n".join(rows) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
