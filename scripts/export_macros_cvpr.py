"""CVPR study macros and tables from the pooled, held-out analyses (logged runs only).

    python scripts/export_macros_cvpr.py [POOL]

POOL (default: the largest pool present) is a '+'-joined list of runs analysed by
scripts/analyze_study.py. All runs share one job definition, so their logs pool. Writes
../paper-pod/results_macros_cvpr.tex and ../paper-pod/tables/{detection_by_verifier,false_flags,
drift_pairs,throughput,precision_downgrade,storybook}.tex. Missing inputs become \\tbd.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _paths import paper_dir, poster_figs  # noqa: E402  (../paper-pod and ../poster, or figures/ standalone)
PAPER = paper_dir()
POOLS = ["study+calib_webgpu-fp32+cross_mac+nvidia48+cross_nvidia+arbiter_cuda+xcal_cuda_fp32+xcal_cuda_tf32+xcal_trt_fp16+xcpu_nvidia48+dense_nvidia48",
         "study+calib_webgpu-fp32+cross_mac+nvidia48+cross_nvidia+arbiter_cuda+xcal_cuda_fp32+xcal_cuda_tf32+xcal_trt_fp16+xcpu_nvidia48",
         "study+calib_webgpu-fp32+nvidia+cross_nvidia+cross_mac+arbiter_cuda"]
CHEATS = [("sub-bk-sdm-small", "BK-SDM-Small"), ("sub-bk-sdm-tiny", "BK-SDM-Tiny"), ("w8", "8-bit weights"),
          ("w4", "4-bit weights"), ("cfg-skip", "CFG skip"), ("cache2", "Cache (every other)"),
          ("cache2-late", "Cache (late only)"), ("step-skip", "Step skip"), ("neg-strip", "Safety strip")]
VERIFIERS = [("Apple GPU", "mps-fp32|mps-fp32"), ("NVIDIA L4", "cuda-fp32|cuda-fp32"),
             ("L4, Apple job", "mps-fp32|cuda-fp32"), ("Browser", "mps-fp32|webgpu-fp32")]
CHEATS_FRESH = [("sub-bk-small", "BK-SDM-Small"), ("sub-bk-tiny", "BK-SDM-Tiny"), ("w8", "8-bit weights"), ("w4", "4-bit weights"),
                ("cfg-skip", "CFG skip"), ("cache2", "Cache (every other)"), ("cache2-late", "Cache (late only)"),
                ("step-skip", "Step skip"), ("neg-strip", "Safety strip")]
MACRO_TAG = {"Apple GPU": "Apple", "NVIDIA L4": "Nvidia", "L4, Apple job": "NvidiaOnApple", "Browser": "Browser"}  # TeX names: letters only
STACK = {"mps-fp32": "Apple GPU", "cpu-fp32": "Apple CPU", "webgpu-fp32": "Browser (WebGPU)", "cuda-fp32": "NVIDIA L4",
         "x86cpu-fp32": "x86 CPU", "cuda-tf32": "L4 TF32", "trt-fp16": "L4 TensorRT FP16",
         "cuda-fp16": "L4 FP16", "mps-fp16": "Apple GPU FP16"}


def j(rel):
    p = RUNS / rel
    return json.loads(p.read_text()) if p.exists() else None


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return f"${m}{{\\times}}10^{{{int(e)}}}$"


def tex_table(name, cols, header, rows, note=""):
    out = ["% Generated by pod/scripts/export_macros_cvpr.py. Do not edit by hand.", f"\\begin{{tabular}}{{{cols}}}", "\\toprule",
           " & ".join(header) + " \\\\", "\\midrule"] + [" & ".join(r) + " \\\\" for r in rows] + ["\\bottomrule", "\\end{tabular}"]
    if note:
        out.append(f"% {note}")
    (PAPER / "tables").mkdir(exist_ok=True)
    (PAPER / "tables" / f"{name}.tex").write_text("\n".join(out) + "\n")


def main():
    pool = sys.argv[1] if len(sys.argv) > 1 else next((p for p in POOLS if (RUNS / p / "summary.json").exists()), POOLS[-1])
    s = j(f"{pool}/summary.json")
    if not s:
        raise SystemExit(f"run scripts/analyze_study.py '{pool}' first")
    m = {"cvprPool": pool.count("+") + 1, "cvprNprompts": s["n_prompts"]}
    fp = s["classes"]["fp32"]
    m.update(cvprHonestXdev=f"{fp['honest_steps_xdev']:,}".replace(",", "{,}"), cvprFlagsMax=fp["honest_false_flags_max"],
             cvprFlagsMaxV=fp["honest_false_flags_maxV"])
    stacks = sorted({w for k in fp["honest_pairs"] for w in k.split("->")})
    m["cvprNstacks"] = len(stacks)

    # detection by verifier (FP32 class, pooled max rule)
    bw = fp["cheats_by_worker"]
    rows, caught = [], {}
    for key, label in CHEATS:
        r = [label]
        for vl, wv in VERIFIERS:
            v = bw.get(f"{key}|{wv}|max")
            r.append(f"{v['P_k2']:.2f}" if v else "--")
            if v:
                caught.setdefault(vl, []).append(v["P_k2"] >= 0.99)
        rows.append(r)
    tex_table("detection_by_verifier", "l" + "c" * len(VERIFIERS), ["Cheat (FP32 job)"] + [v for v, _ in VERIFIERS], rows,
              "P(detect) with k=2 uniformly random challenges; thresholds held out per prompt (pooled max rule).")
    for vl, cs in caught.items():
        m[f"cvprCaught{MACRO_TAG[vl]}"] = f"{sum(cs)} of {len(cs)}"
    # prompts behind each column, for the caption; the assert keeps the caption's wording true to the logs
    ns = {vl: {key: bw[f"{key}|{wv}|max"]["n"] for key, _ in CHEATS if f"{key}|{wv}|max" in bw} for vl, wv in VERIFIERS}
    typ = {vl: max(set(d.values()), key=list(d.values()).count) for vl, d in ns.items() if d}
    odd = [(vl, k, n) for vl, d in ns.items() for k, n in d.items() if n != typ[vl]]
    others = {n for vl, n in typ.items() if vl != "NVIDIA L4"}
    assert len(others) == 1 and [(vl, k) for vl, k, _ in odd] == [("Browser", "w8")], (typ, odd)
    m.update(cvprDetN=others.pop(), cvprDetNNvidia=typ["NVIDIA L4"], cvprDetNBrowserWeight=odd[0][2])

    # false flags by class and rule
    rows = []
    for cls in ("fp32", "tf32", "fp16", "bf16"):
        c = s["classes"].get(cls)
        if not c or c.get("uncalibrated"):
            continue
        n = c["honest_steps_xdev"]
        cell = lambda r: f"{c[f'honest_false_flags_{r}']}/{n}" if f"honest_false_flags_{r}" in c else "n/a"
        rows.append([cls.upper(), f"{n:,}".replace(",", "{,}"), cell("max"), cell("maxV")])
    # (the old step-pooled "conformal" column is dropped: steps of one request are not independent; see conformal.tex)
    tex_table("false_flags", "lccc", ["Class", "Honest cross-device steps", "Max rule (pooled)", "Max rule (per stack)"], rows)

    # drift pairs (FP32 class)
    rows = []
    for k, v in sorted(fp["honest_pairs"].items()):
        a, b = k.split("->")
        if a != b:
            rows.append([f"{STACK.get(a, a)} $\\to$ {STACK.get(b, b)}", str(v["n"]), sci(v["median"]), sci(v["max"])])
    tex_table("drift_pairs", "lccc", ["Worker $\\to$ verifier", "$n$", "median $r$", "max $r$"], rows)

    # precision downgrade
    dg = j("precision_downgrade.json")
    if dg:
        rows = [[STACK.get(w, w), f"{d['flagged']}/{d['steps']}", f"{d['P_k2_mean']:.2f}"] for w, d in sorted(dg["downgrades"].items())]
        tex_table("precision_downgrade", "lcc", ["Job run as (claimed FP32)", "Steps flagged", "P(detect), $k{=}2$"], rows)
        if "cuda-tf32" in dg["downgrades"]:
            d = dg["downgrades"]["cuda-tf32"]
            m["cvprTfFlag"] = f"{d['flagged']}/{d['steps']}"
    tf = s["classes"].get("tf32", {}).get("honest_pairs", {}).get("cuda-tf32->cuda-fp32")
    if tf:
        m["cvprTfMed"] = sci(tf["median"])

    # throughput
    b, a = j("bench_nvidia.json") or {}, j("bench_backends.json") or {}
    rows = []
    for dev, stack, d, keys in (("Apple M1 Pro GPU", "PyTorch MPS", a, ["mps-fp16", "mps-fp32"]), ("Apple M1 Pro CPU", "PyTorch", a, ["cpu-fp32"]),
                                ("NVIDIA L4", "PyTorch CUDA", b, ["cuda-fp16", "cuda-tf32", "cuda-fp32"]),
                                ("NVIDIA L4", "TensorRT", b, ["trt-fp16"]), ("x86 CPU (8 vCPU)", "PyTorch", b, ["cpu-fp32"])):
        vals = [f"{d[k]['step_s']:.3f}" for k in keys if k in d and "step_s" in d[k]]
        if vals:
            rows.append([dev, stack, " / ".join(k.split("-")[1].upper() for k in keys if k in d), " / ".join(vals)])
    tex_table("throughput", "llcc", ["Device", "Stack", "Precision", "s per guided step"], rows)
    if "trt-fp16" in b and "cuda-fp16" in b:
        m["cvprTrtStep"] = f"{b['trt-fp16']['step_s']:.3f}"
        m["cvprTrtSpeedup"] = f"{b['cuda-fp16']['step_s'] / b['trt-fp16']['step_s']:.2f}"
    if "cuda-tf32" in b and "cuda-fp32" in b:
        m["cvprTfSaving"] = f"{100 * (1 - b['cuda-tf32']['step_s'] / b['cuda-fp32']['step_s']):.0f}"

    # storybook case study
    rows = []
    for run in ("storybook", "storybook_cuda"):
        render = j(f"{run}/render.json")
        for v in ("webgpu-fp32", "cuda-fp32"):
            f = RUNS / run / f"verify_{v}.judged.jsonl"
            if not render or not f.exists():
                continue
            recs = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
            kind = lambda r: render["pages"][r["page"]][r["node"]]
            tn = sum(kind(r) == "honest" and r["accepted"] for r in recs)
            nh = sum(kind(r) == "honest" for r in recs)
            tp = sum(kind(r) != "honest" and not r["accepted"] for r in recs)
            nc = sum(kind(r) != "honest" for r in recs)
            secs = sorted(r["secs"] for r in recs)
            rows.append([STACK.get(render["device"], render["device"]), STACK.get(v, v), f"{tn}/{nh}", f"{tp}/{nc}", f"{secs[len(secs) // 2]:.1f}"])
    if rows:
        tex_table("storybook", "llccc", ["Rendered on", "Verified on", "Honest accepted", "Cheats rejected", "s / page"], rows)

    # per-tier held-out false flags (pooled max rule)
    fl = fp.get("honest_false_flag_pairs_max", {})
    br_n = sum(v["n"] for k, v in fp["honest_pairs"].items() if k.endswith("->webgpu-fp32") and not k.startswith("webgpu"))
    m.update(cvprNativeFA=sum(v for k, v in fl.items() if not k.endswith("->webgpu-fp32")),
             cvprNativeN=f"{fp['honest_steps_xdev'] - br_n:,}".replace(",", "{,}"),
             cvprBrowserFA=sum(v for k, v in fl.items() if k.endswith("->webgpu-fp32")), cvprBrowserN=f"{br_n:,}".replace(",", "{,}"))
    esc = j("escalation_webgpu-fp32_to_cuda-fp32.json")
    if esc:
        m.update(cvprEscN=esc["escalated"], cvprEscConfirmed=esc["confirmed"], cvprEscRefMax=f"{esc['ref_over_max']:.2f}")
    if dg:
        for w, tag in (("cuda-fp16", "FpSixteen"), ("mps-fp16", "AppleFpSixteen")):
            if w in dg["downgrades"]:
                m[f"cvprDowngrade{tag}"] = f"{dg['downgrades'][w]['flagged']:,}/{dg['downgrades'][w]['steps']:,}".replace(",", "{,}")
        if "cuda-tf32" in dg["downgrades"]:
            d = dg["downgrades"]["cuda-tf32"]
            m["cvprTfFlag"] = f"{d['flagged']:,}/{d['steps']:,}".replace(",", "{,}")
    tfp = s["classes"].get("tf32", {}).get("honest_pairs", {})
    xmeds = sorted(v["median"] for k, v in fp["honest_pairs"].items() if k.split("->")[0] != k.split("->")[1])
    if "cuda-tf32->cuda-fp32" in tfp and xmeds:
        m["cvprTfRatio"] = f"{tfp['cuda-tf32->cuda-fp32']['median'] / xmeds[len(xmeds) // 2]:.0f}"
    xv = [v for k, v in fp["honest_pairs"].items() if {"mps-fp32", "cuda-fp32"} == set(k.split("->"))]
    if xv:
        m.update(cvprXvMed=sci(min(v["median"] for v in xv)), cvprXvMax=sci(max(v["max"] for v in xv)))
    xc = fp["honest_pairs"].get("cuda-fp32->x86cpu-fp32")
    if xc:
        m.update(cvprXcpuN=f"{xc['n']:,}".replace(",", "{,}"), cvprXcpuMax=sci(xc["max"]))
    # wall time per page
    if "cuda-fp32" in b:
        m["cvprRenderSec"] = f"{25 * b['cuda-fp32']['step_s']:.1f}"
    # fresh, pre-registered storybook evaluation
    fr = j("storybook_fresh/result.json")
    if fr:
        # distinct pages: node A (honest) and node B (deviating) each render every page
        m.update(cvprFreshPages=len({p["page"] for p in fr["pages"]}), cvprFreshHonest=fr["honest_pages"],
                 cvprFreshHonestOK=fr["honest_accepted_final"], cvprFreshHonestFlagged=fr["honest_flagged_tier1"],
                 cvprFreshDev=fr["deviating_pages"], cvprFreshRejected=fr["deviating_rejected_final"],
                 cvprFreshExpected=f"{fr['expected_rejected_k2']:.1f}", cvprFreshMinOver=int(fr["detectable_min_over_reference"]),
                 cvprBrowserCheckSec=f"{fr['median_secs']['browser_check']:.1f}")
        rows = []
        for k, label in CHEATS_FRESH:
            v = fr["by_kind"].get(k)
            if v:
                rows.append([label, ", ".join(map(str, v["m"])), ", ".join(f"{x:.2f}" for x in v["P_k2"]), f"{v['rejected']}/{v['pages']}"])
        rows.append(["Honest (node A)", "0 (all 16)", "--", f"{fr['honest_accepted_final']}/{fr['honest_pages']} accepted"])
        tex_table("fresh", "lccc", ["Node B deviation", "detectable steps $m$", "$P$(detect), $k{=}2$", "rejected"], rows)
    dm = j("dense_margin.json")
    sc = j("scale240_report.json")  # the nine shortcuts on 240 further prompts (scripts/shortcut_scale.py, scale_report.py)
    sc = sc if sc and sc.get("prompts") == 240 else None  # only the finished run enters the paper
    lo = [x for x in ((fr or {}).get("detectable_min_over_reference"), (dm or {}).get("min_over_detectable"),
                      (sc or {}).get("min_over_changed")) if x is not None]
    commas = lambda x: f"{x:,}".replace(",", "{,}")
    if lo:
        m["cvprShortcutMinOver"] = int(min(lo))
        m["cvprShortcutTraj"] = commas((fr["deviating_pages"] if fr else 0) + (dm["trajectories"] if dm else 0) + (sc["trajectories"] if sc else 0))
    if sc:
        m.update(cvprScalePrompts=sc["prompts"], cvprScaleTraj=commas(sc["trajectories"]), cvprScaleChanged=commas(sc["changed_steps"]),
                 cvprScaleMissed=sc["changed_not_flagged"], cvprScaleMinOver=int(sc["min_over_changed"]),
                 cvprScaleCaught=f"{sc['caught_k2']} of {len(sc['shortcuts'])}",
                 cvprScaleCacheKtwo=f"{sc['shortcuts']['cache2']['P_k2']:.2f}", cvprScaleCacheLateKtwo=f"{sc['shortcuts']['cache2-late']['P_k2']:.2f}")
    # full-cost attacks
    f = RUNS / "adaptive" / "outputs.jsonl"
    if f.exists():
        rs = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
        med = lambda v: sorted(v)[len(v) // 2]
        m["cvprAttackN"] = len(rs)
        for a_, tag in (("steer33", "SteerLo"), ("steer95", "SteerHi"), ("splice12", "SpliceMid"), ("splice20", "SpliceLate")):
            ps = [r["attacks"][a_]["psnr_vs_honest"] for r in rs]
            lp = [r["attacks"][a_]["latent_progress"] for r in rs]
            m[f"cvpr{tag}PsnrMed"], m[f"cvpr{tag}PsnrMin"] = f"{med(ps):.0f}", f"{min(ps):.1f}"
            m[f"cvpr{tag}ProgMax"], m[f"cvpr{tag}ProgMed"] = f"{100 * max(lp):.1f}", f"{100 * med(lp):.2f}"
        m["cvprTargetPsnrMed"] = f"{med([r['psnr_target_vs_honest'] for r in rs]):.0f}"
    # optimised steering (scripts/optimal_steer.py): adjoint directions inside the same per-step budget
    f_opt = RUNS / "adaptive_opt" / "outputs.jsonl"
    if f_opt.exists():
        ro = [json.loads(l) for l in f_opt.read_text().splitlines() if l.strip()]
        med_ = lambda v: sorted(v)[len(v) // 2]
        m["cvprOptN"] = len(ro)
        for a_, tag in (("max95", "OptHi"), ("max33", "OptLo")):
            ps = [r["attacks"][a_]["psnr_vs_honest"] for r in ro]
            lp = [r["attacks"][a_]["latent_progress"] for r in ro]
            m.update({f"cvpr{tag}PsnrMed": f"{med_(ps):.0f}", f"cvpr{tag}PsnrMin": f"{min(ps):.1f}",
                      f"cvpr{tag}ProgMax": f"{100 * max(lp):.1f}", f"cvpr{tag}ProgMed": f"{100 * med_(lp):.1f}",
                      f"cvpr{tag}BelowThirty": sum(x < 30 for x in ps)})
        # the component of the displacement that points at the chosen target, over both objectives
        m["cvprOptTowardMax"] = f"{100 * max(r['attacks'][k]['toward_target'] for r in ro for k in ('opt95', 'max95')):.1f}"
        f_old = RUNS / "adaptive" / "outputs.jsonl"
        if f_old.exists():
            old_ = {r["prompt"]: r["attacks"]["steer95"]["latent_progress"] for r in map(json.loads, f_old.read_text().splitlines()) if r}
            m["cvprOptGain"] = f"{med_([r['attacks']['max95']['latent_progress'] / old_[r['prompt']] for r in ro if old_.get(r['prompt'])]):.0f}"
        m["cvprOptPowerGain"] = f"{med_([r['power'][-1] / r['power'][0] for r in ro]):.1f}"
        if f_old.exists():  # fixed and optimised steering side by side (supplement)
            ol = [json.loads(l) for l in f_old.read_text().splitlines() if l.strip()]
            rows = []
            for label, src, key in (("Fixed, $c{=}0.33$", ol, "steer33"), ("Fixed, $c{=}0.95$", ol, "steer95"),
                                    ("Optimized, $c{=}0.33$", ro, "max33"), ("Optimized, $c{=}0.95$", ro, "max95")):
                ps = [r["attacks"][key]["psnr_vs_honest"] for r in src]
                lp = [100 * r["attacks"][key]["latent_progress"] for r in src]
                rows.append([label, f"{med_(lp):.2f} / {max(lp):.1f}", f"{med_(ps):.0f} / {min(ps):.1f}", f"{sum(x < 30 for x in ps)} / {len(ps)}"])
            tex_table("steering", "lccc", ["Steering", "displacement (\\%), med / max", "PSNR (dB), med / min", "below 30 dB"], rows)
    xo = j("adaptive_opt/xverify_summary.json")  # these trajectories re-checked on another stack (scripts/attack_xverify.py)
    if xo:
        for a_, tag in (("max95", "OptHi"), ("max33", "OptLo")):
            v = xo.get("summary", {}).get(a_)
            if v:
                m[f"cvpr{tag}XvOver"], m[f"cvpr{tag}XvN"], m[f"cvpr{tag}XvSteps"] = v["steps_over"], v["trajectories"], v["steps"]
                m[f"cvpr{tag}XvMaxOver"] = f"{v['max_over_tau']:.2f}"
    xa = j("adaptive/xverify_summary.json")
    if xa:
        for a_, tag in (("steer33", "SteerLo"), ("steer95", "SteerHi"), ("splice20", "SpliceLate")):
            v = xa.get("summary", {}).get(a_)
            if v:
                m[f"cvpr{tag}XvOver"], m[f"cvpr{tag}XvN"], m[f"cvpr{tag}XvSteps"] = v["steps_over"], v["trajectories"], v["steps"]
    od = j("output_drift_fp32.json")
    if od:
        m["cvprOutPsnrMin"] = f"{min(v['psnr_min'] for v in od['pairs'].values()):.1f}"
        m["cvprOutPsnrMed"] = f"{min(v['psnr_median'] for v in od['pairs'].values()):.0f}"
    # request-level split conformal
    cf = j("conformal_requests.json")
    if cf and cf.get("usable"):
        m.update(cvprConfN=cf["calibration_requests"], cvprConfFit=cf["fit_requests"], cvprConfAlpha=f"{100 * cf['alpha']:.0f}",
                 cvprConfRank=cf["rank"], cvprConfSameFlag=cf["test_same_stacks"]["flagged"], cvprConfSameN=cf["test_same_stacks"]["requests"],
                 cvprConfCaught=cf["caught_k2_ge_099"])
        rows = [[STACK.get(k.split("->")[0], k.split("->")[0]) + " $\\to$ " + STACK.get(k.split("->")[1], k.split("->")[1]),
                 f"{v['flagged']}/{v['requests']}"] for k, v in cf["test_requests_flagged"].items()]
        tex_table("conformal", "lc", ["Held-out honest requests (worker $\\to$ verifier)", "flagged"], rows)
    sr = j("sana_report.json")
    if sr:
        f32 = sr["classes"].get("fp32", {})
        pr = f32.get("pairs", {}).get("cuda-fp32->x86cpu-fp32")
        m.update(cvprSanaPrompts=sr["prompts"], cvprSanaCaught=f"{sr['fp32_caught_k2']} of {len(sr['fp32_detection'])}")
        if "cache2" in sr["fp32_detection"]:
            m["cvprSanaCacheKtwo"] = f"{sr['fp32_detection']['cache2']['P_k2']:.2f}"
        if f32:
            m.update(cvprSanaFlags=f32["false_flags_max"], cvprSanaHonestN=f"{f32['honest_steps_xdev']:,}".replace(",", "{,}"))
        if pr:
            m.update(cvprSanaXvMed=sci(pr["median"]), cvprSanaXvMax=sci(pr["max"]))
        lf = sorted((f["over"] for f in sr.get("fp32_loo_flags", [])), reverse=True)
        if lf:
            m["cvprSanaOutlier"] = f"{lf[0]:.1f}"
            if len(lf) > 1:
                m.update(cvprSanaRestN=len(lf) - 1, cvprSanaRestMax=f"{lf[1]:.2f}")
        b16 = sr["classes"].get("bf16", {}).get("pairs", {}).get("cuda-bf16->cuda-fp32")
        if b16:
            m["cvprSanaBfMed"] = sci(b16["median"])
        for w, tag in (("cuda-bf16", "Bf"), ("cuda-tf32", "Tf")):
            d = sr["downgrades"].get(w)
            if d and d["steps"]:
                m[f"cvprSana{tag}Flag"] = f"{d['flagged']:,}/{d['steps']:,}".replace(",", "{,}")
    # further model families (scripts/family_study.py; one report each from scripts/sana_report.py <run>)
    num = lambda x: f"{x:,}".replace(",", "{,}")
    for run, tag in (("sdxl", "Sdxl"), ("wan", "Wan")):
        fam = j(f"{run}_report.json")
        if not fam:
            continue
        f32 = fam["classes"].get("fp32", {})
        det = fam["fp32_detection"]
        m[f"cvpr{tag}Prompts"] = fam["prompts"]
        m[f"cvpr{tag}Caught"] = f"{fam['fp32_caught_k2']} of {len(det)}"
        secs = (j(f"{run}/summary.json") or {}).get("verify_secs_per_step", {}).get("cuda-fp32")  # one re-checked step on the L4
        if secs:
            m.update({f"cvpr{tag}StepSec": f"{secs:.1f}" if secs < 10 else f"{secs:.0f}", f"cvpr{tag}CheckSec": f"{2 * secs:.0f}",
                      f"cvpr{tag}JobMin": f"{25 * secs / 60:.0f}"})
        for key, t2 in (("cache2", "Cache"), ("cache2-late", "CacheLate")):
            if key in det:
                m[f"cvpr{tag}{t2}Ktwo"] = f"{det[key]['P_k2']:.2f}"
        if f32:
            m[f"cvpr{tag}Flags"], m[f"cvpr{tag}HonestN"] = f32["false_flags_max"], num(f32["honest_steps_xdev"])
            for pair, who in (("cuda-fp32->mps-fp32", "Apple"), ("cuda-fp32->x86cpu-fp32", "Cpu"), ("cuda-fp32->a100-fp32", "Ahundred"),
                              ("cuda-fp32->t4-fp32", "Tfour")):
                pr = f32["pairs"].get(pair)
                if pr:
                    m.update({f"cvpr{tag}{who}N": num(pr["n"]), f"cvpr{tag}{who}Med": sci(pr["median"]), f"cvpr{tag}{who}Max": sci(pr["max"])})
            if f32["pairs"]:
                m.update({f"cvpr{tag}Stacks": len(f32["pairs"]), f"cvpr{tag}XvMax": sci(max(v["max"] for v in f32["pairs"].values())),
                          f"cvpr{tag}XvMed": sci(max(v["median"] for v in f32["pairs"].values()))})
        lf = sorted((f["over"] for f in fam.get("fp32_loo_flags", [])), reverse=True)
        if lf:
            m[f"cvpr{tag}FlagOver"] = f"{lf[0]:.2f}"
        for w, t2 in (("tf32", "Tf"), ("fp16", "Fp"), ("bf16", "Bf")):
            pr = fam["classes"].get(w, {}).get("pairs", {}).get(f"cuda-{w}->cuda-fp32")
            if pr:
                m[f"cvpr{tag}{t2}Med"] = sci(pr["median"])
            d = fam["downgrades"].get(f"cuda-{w}")
            if d and d["steps"]:
                m[f"cvpr{tag}{t2}Flag"] = f"{num(d['flagged'])}/{num(d['steps'])}"
    # further NVIDIA GPUs, judged with the thresholds frozen before they joined (scripts/xgpu_report.py)
    xg = j("xgpu_report.json")
    if xg and xg.get("honest_fp32_cross", {}).get("steps"):
        hc = xg["honest_fp32_cross"]
        cross = {k: v for k, v in xg["honest_fp32"].items() if not v["same_gpu"]}
        m.update(cvprXgSteps=num(hc["steps"]), cvprXgFlagged=hc["flagged"], cvprXgMaxOver=f"{hc['max_over_tau']:.2f}",
                 cvprXgMax=sci(hc["max"]), cvprXgMed=sci(hc["median_of_medians"]), cvprXgPairs=len(cross),
                 cvprXgGpus=len(xg["gpus"]), cvprXgSame=sum(v["flagged"] for v in xg["honest_fp32"].values() if v["same_gpu"]))
        for tag, g in xg["gpus"].items():
            t = tag.upper() if tag[0] != "a" else "A" + tag[1:]   # t4 -> T, a100 -> A (TeX names: letters only)
            name = "".join(ch for ch in t if ch.isalpha())[:1]
            st = g.get("step_s", {})
            if "cuda-fp32" in st:
                m[f"cvprXg{name}StepFp"] = f"{st['cuda-fp32']:.2f}"
            if "cuda-tf32" in st and "cuda-fp32" in st:
                m[f"cvprXg{name}TfSaving"] = f"{100 * (1 - st['cuda-tf32'] / st['cuda-fp32']):.0f}"
            sc = xg["shortcuts"].get(f"{tag}-fp32")
            if sc:
                m[f"cvprXg{name}Caught"] = f"{sc['caught_k2']} of {sum(isinstance(v, dict) for v in sc.values())}"
        real = {k: v for k, v in xg["precision"].items() if not v["bit_identical"]}
        if real:
            m["cvprXgDownFlag"] = f"{num(sum(v['flagged'] for v in real.values()))}/{num(sum(v['n'] for v in real.values()))}"
        rows = [[k.replace("->", " $\\to$ ").replace("cuda-fp32", "L4").replace("-fp32", "").replace("t4", "T4").replace("a100", "A100").replace("mps", "Apple GPU"),
                 num(v["n"]), sci(v["median"]), sci(v["max"]), f"{v['flagged']}", f"{v['max_over_tau']:.2f}"] for k, v in cross.items()]
        tex_table("xgpu_pairs", "lrcccc", ["Worker $\\to$ verifier", "steps", "median $r$", "max $r$", "flagged", "max $r/\\tau$"], rows)
    tt = j("two_tier_power.json")
    if tt:
        m.update(cvprTwoTierCommon=tt["with_reference_check"], cvprTwoTierConfirmed=tt["reference_confirmed"])
    dc = j("detect_vs_cost.json")
    if dc:
        m["cvprCostPrompts"] = dc["prompts"]
        for key, tag in (("cache2", "Cache"), ("cache2-late", "CacheLate")):
            sr = dc["series"].get(key)
            if sr:
                m[f"cvpr{tag}Ktwo"] = f"{sr['mean']['2']:.2f}"
                ks = [int(k) for k, v in sr["mean"].items() if v is not None and v >= 0.99]
                m[f"cvpr{tag}KNine"] = min(ks) if ks else "${>}12$"
    br = [v["max"] for k, v in fp["honest_pairs"].items() if "webgpu" in k]
    if br:
        m["cvprBrowserMax"] = sci(max(br))
    f16 = s["classes"].get("fp16", {}).get("honest_pairs", {})
    if "cuda-fp16->cuda-fp32" in f16:
        m["cvprFpSixteenMed"] = sci(f16["cuda-fp16->cuda-fp32"]["median"])
    if "mps-fp16->trt-fp16" in f16:
        m["cvprTrtDriftMed"] = sci(f16["mps-fp16->trt-fp16"]["median"])
    sbc = RUNS / "storybook_cuda" / "verify_cuda-fp32.judged.jsonl"
    if sbc.exists():
        secs = sorted(json.loads(l)["secs"] for l in sbc.read_text().splitlines() if l.strip())
        m["cvprCheckSecLfour"] = f"{secs[len(secs) // 2]:.1f}"
    tz = j("storybook_fresh/taus_fp32.json")
    if tz:
        m["cvprTauMin"], m["cvprTauMax"] = sci(min(tz["tau"].values())), sci(max(tz["tau"].values()))
    if fr:
        pk = [x for k in ("cache2", "cache2-late") for x in fr["by_kind"].get(k, {}).get("P_k2", [])]
        if pk:
            m["cvprFreshCacheP"] = f"{min(pk):.2f}\\text{{--}}{max(pk):.2f}"  # en dash that also works in math mode

    # equal-budget baseline: replaying whole jobs (scripts/baseline_compare.py) versus k = 2 step checks
    bc = j("baseline_compare.json")
    if bc and dg:
        h, dv, b = bc["honest"], bc["deviations"], bc["budget_k2"]
        every = ["sub-bk-sdm-small", "sub-bk-sdm-tiny", "w8", "w4", "cfg-skip", "neg-strip", "step-skip"]
        pod = {k: bw[f"{k}|cuda-fp32|cuda-fp32|max"]["P_k2"] for k in every + ["cache2", "cache2-late"]}
        replay = [min(dv[k]["replay_detect"] for k in every), dv["cache2"]["replay_detect"], dv["cache2-late"]["replay_detect"],
                  dv["tf32-as-fp32"]["replay_detect"], dv["fp16-as-fp32"]["replay_detect"]]
        ours = [min(pod[k] for k in every), pod["cache2"], pod["cache2-late"],
                dg["downgrades"]["cuda-tf32"]["P_k2_min"], dg["downgrades"]["cuda-fp16"]["P_k2_min"]]
        fmt = lambda xs: [f"{x:.2f}" for x in xs]
        tex_table("baselines", "lcccccc",
                  ["Verification", "Cost", "Every-step", "Cache", "Late cache", "TF32", "FP16"],
                  [["Replay every job", "100\\%"] + fmt(replay),
                   [f"Replay {100 * b:.0f}\\% of jobs", f"{100 * b:.0f}\\%"] + fmt([b * x for x in replay]),
                   ["\\pod, $k{=}2$", f"{100 * b:.0f}\\%"] + fmt(ours)],
                  "Per-job detection probability. Replay: final-latent tolerance, Apple GPU replays L4 jobs (baseline_compare.py).")
        step = fp["honest_pairs"]["cuda-fp32->mps-fp32"]  # the same worker -> verifier pair, per step
        m.update(cvprBaseN=bc["prompts"], cvprBaseHonestMed=sci(h["median"]), cvprBaseHonestMax=sci(h["max"]),
                 cvprBaseTail=f"{h['max'] / h['median']:.0f}", cvprBaseStepTail=f"{step['max'] / step['median']:.0f}",
                 cvprBaseFlagged=h["flagged"], cvprBaseBitExact=h["bit_exact_pairs"],
                 cvprBaseReplayTf=f"{100 * dv['tf32-as-fp32']['replay_detect']:.0f}",
                 cvprBaseReplayFp=f"{100 * dv['fp16-as-fp32']['replay_detect']:.0f}",
                 cvprBaseBudget=f"{100 * b:.0f}")

    # how visible each deviation is (scripts/perceptual_table.py): saving, PSNR to the honest image, who detects it
    pv = j("perceptual.json")
    if pv:
        names = {"tf32-as-fp32": "TF32 run as FP32", "fp16-as-fp32": "FP16 run as FP32", "cache2-late": "Cache (late only)",
                 "cache2": "Cache (every other)", "step-skip": "Step skip", "cfg-skip": "CFG skip",
                 "sub-bk-sdm-small": "BK-SDM-Small", "sub-bk-sdm-tiny": "BK-SDM-Tiny", "w8": "8-bit weights (simulated)",
                 "w4": "4-bit weights (simulated)", "neg-strip": "Safety strip"}
        rows = [[names[k], "--" if v["saved"] is None else f"{100 * v['saved']:.0f}\\%", f"{v['psnr_median']:.0f}",
                 f"{v['replay_detect']:.2f}", f"{v['pod_k2']:.2f}"] for k, v in pv["rows"].items()]
        tex_table("visible", "lcccc", ["Deviation", "Saved", "PSNR (dB)", "Replay", "\\pod, $k{=}2$"], rows,
                  "Saved compute, median PSNR to the honest image, detection by a full replay and by two step checks.")
        r = pv["rows"]
        m.update(cvprVisTfPsnr=f"{r['tf32-as-fp32']['psnr_median']:.0f}", cvprVisFpPsnr=f"{r['fp16-as-fp32']['psnr_median']:.0f}",
                 cvprVisFpSaved=f"{100 * r['fp16-as-fp32']['saved']:.0f}", cvprVisLatePsnr=f"{r['cache2-late']['psnr_median']:.0f}",
                 cvprVisN=pv["prompts"])

    lines = ["% Generated by pod/scripts/export_macros_cvpr.py from logged runs. Do not edit by hand.", f"% pool: {pool}"]
    assert all(k.isalpha() for k in m), [k for k in m if not k.isalpha()]  # TeX control words are letters only
    lines += [f"\\newcommand{{\\{k}}}{{{v}\\xspace}}" for k, v in m.items()]
    (PAPER / "results_macros_cvpr.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("tables:", sorted(p.name for p in (PAPER / "tables").glob("*.tex")))


