"""SANA-1.6B (second model family) results for the paper, from runs/sana (scripts/sana_study.py on the NVIDIA L4 and
its x86 CPU). Runs scripts/analyze_study.py sana first (held-out per prompt, pooled max rule), then adds the
precision-downgrade test: honest BF16 / TF32 trajectories submitted as FP32 jobs, judged against the FP32-class
thresholds (tau_i = 1.5 x max honest cross-device FP32 r_i, leave-one-prompt-out).

    python scripts/sana_report.py
Writes runs/sana_report.json and ../paper-pod/tables/sana.tex.
"""
import json
import math
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _paths import paper_dir, poster_figs  # noqa: E402  (../paper-pod and ../poster, or figures/ standalone)
PAPER = paper_dir()
LABEL = {"sub-sana600": "SANA-0.6B substitute", "w8": "8-bit weights", "w4": "4-bit weights", "cfg-skip": "CFG skip",
         "cache2": "Cache (every other)", "cache2-late": "Cache (late only)", "step-skip": "Step skip", "neg-strip": "Safety strip"}


def cls(b):
    return b.rsplit("-", 1)[-1]


def main():
    subprocess.run([sys.executable, str(ROOT / "scripts" / "analyze_study.py"), "sana"], check=True, capture_output=True)
    s = json.loads((RUNS / "sana" / "summary.json").read_text())
    recs = [json.loads(l) for l in (RUNS / "sana" / "checks.jsonl").read_text().splitlines() if l.strip()]
    fp = s["classes"].get("fp32", {})
    out = {"prompts": s["n_prompts"], "classes": {}}
    for c, d in s["classes"].items():
        if d.get("uncalibrated"):
            continue
        out["classes"][c] = {"honest_steps_xdev": d["honest_steps_xdev"], "false_flags_max": d["honest_false_flags_max"],
                             "pairs": {k: {"n": v["n"], "median": v["median"], "max": v["max"]} for k, v in d["honest_pairs"].items()
                                       if k.split("->")[0] != k.split("->")[1]}}
    bw = fp.get("cheats_by_worker", {})
    det = {k.split("|")[0]: v for k, v in bw.items() if k.endswith("|cuda-fp32|cuda-fp32|max")}
    out["fp32_detection"] = {k: {"P_k2": v["P_k2"], "flag_frac": v["flag_frac"], "n": v["n"]} for k, v in det.items()}
    out["fp32_caught_k2"] = sum(v["P_k2"] >= 0.99 for v in det.values())
    # precision downgrade: honest BF16/TF32 trajectories judged as FP32 jobs
    cal = [r for r in recs if r["kind"] == "honest" and cls(r["worker"]) == "fp32" and cls(r["verifier"]) == "fp32"
           and r["worker"] != r["verifier"]]
    dg = {}
    for w in sorted({r["worker"] for r in recs if r["kind"] == "honest" and cls(r["worker"]) != "fp32"}):
        flags = steps = 0
        for r in (x for x in recs if x["kind"] == "honest" and x["worker"] == w and cls(x["verifier"]) == "fp32"):
            acc = defaultdict(list)
            for c in cal:
                if c["prompt"] != r["prompt"]:
                    for x in c["checks"]:
                        acc[x["i"]].append(x["ratio"])
            for x in r["checks"]:
                if acc.get(x["i"]):
                    steps += 1
                    flags += x["ratio"] > 1.5 * max(acc[x["i"]])
        dg[w] = {"flagged": flags, "steps": steps}
    out["downgrades"] = dg
    # held-out FP32 flags in detail: r / (1.5 x max over the other prompts at that step)
    by_step = defaultdict(dict)
    for c in cal:
        for x in c["checks"]:
            by_step[x["i"]][c["prompt"]] = max(x["ratio"], by_step[x["i"]].get(c["prompt"], 0.0))
    over = sorted((v / (1.5 * max(o for q, o in d.items() if q != p)), p, i)
                  for i, d in by_step.items() for p, v in d.items() if len(d) > 1)
    out["fp32_loo_flags"] = [{"prompt": p, "step": i, "over": round(o, 3)} for o, p, i in over if o > 1]
    (RUNS / "sana_report.json").write_text(json.dumps(out, indent=1))
    rows = []
    for k, label in LABEL.items():
        v = det.get(k)
        if v:
            rows.append(f"{label} & {100 * v['flag_frac']:.0f}\\% & {v['P_k2']:.2f} \\\\")
    tbl = ["% Generated by pod/scripts/sana_report.py. Do not edit by hand.", "\\begin{tabular}{lcc}", "\\toprule",
           "Deviation (FP32 job) & Flagged steps & $P$(detect), $k{=}2$ \\\\", "\\midrule"] + rows + ["\\bottomrule", "\\end{tabular}"]
    (PAPER / "tables" / "sana.tex").write_text("\n".join(tbl) + "\n")
    print(json.dumps({k: v for k, v in out.items() if k != "classes"}, indent=1))
    for c, d in out["classes"].items():
        print(c, d["honest_steps_xdev"], "false flags", d["false_flags_max"], {k: f"{v['median']:.1e}/{v['max']:.1e}" for k, v in d["pairs"].items()})


if __name__ == "__main__":
    main()
